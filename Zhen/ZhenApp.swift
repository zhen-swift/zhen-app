// ZhenApp.swift — the entry point, and the Info.plist generator.
//
// The generator is here rather than in a script because of document 03's note on the
// Local Network permission: every Bonjour service type the discovery layer browses must
// appear in `NSBonjourServices`, and a type that is browsed but undeclared **returns
// nothing, silently, with no error anywhere**. A hand-maintained array in a plist and a
// list in Swift will drift; the only arrangement that cannot drift is one list, read by
// both. `Scripts/build-app.sh` invokes `--print-info-plist` and writes what comes out.

import ZhenCore
import SwiftUI

@main
enum Entry {
    static func main() {
        // Before any UI, so the build script can ask a GUI binary a question without a
        // window appearing.
        if CommandLine.arguments.contains("--print-info-plist") {
            print(InfoPlist.xml())
            return
        }
        ZhenApp.main()
    }
}

struct ZhenApp: App {
    var body: some Scene {
        WindowGroup {
            RootView()
                // The minimum is measured by rendering the window, not by summing
                // tokens and not by asking `fittingSize` — which cannot see the table
                // at all, because a `ScrollView` reports no minimum for what it holds.
                // See `Metrics.windowMinWidth`; stage 4 brought it from a declared
                // 1000 to a measured 978, four points above the width where the device
                // row stops fitting its pane. Twenty-two points, which is what five
                // legible columns cost. Stage 8 is what buys more.
                //
                // The height is still a bare 560. Every room is a scroll view, so
                // nothing vertical asserts a minimum for this to be derived from; it is
                // a judgement about the smallest window worth having rather than a
                // measurement, and it is written as a literal so it does not look like
                // one.
                .frame(minWidth: Metrics.windowMinWidth, minHeight: 560)
                .background(Palette.surface)
        }
        .defaultSize(width: 1182, height: 760)
        .windowToolbarStyle(.unifiedCompact)
    }
}

/// The bundle's `Info.plist`, generated from the same list the scanner browses.
enum InfoPlist {
    /// The bundle identifier. Document 03's bundle identity section: nothing a person
    /// sees in System Settings may look anonymous.
    static let bundleIdentifier = "com.jctec.zhen"
    /// The display name.
    static let bundleName = "Zhen"
    /// The icns inside Contents/Resources, without its extension.
    ///
    /// Both keys are written. `CFBundleIconFile` is what a bundle assembled outside
    /// Xcode needs, which is what `Scripts/build-app.sh` produces; `CFBundleIconName`
    /// is what an asset-catalogue build sets, and Login Items reads the asset name
    /// when one is present. Writing both means the same plist serves either build
    /// without a branch, and neither key is wrong when the other is unused.
    static let iconFile = "Zhen"

    /// The version, from core, which is where the repository declares it once.
    static let version = ZhenVersion.current

    /// Why the app wants the Local Network permission, in the words the system shows.
    ///
    /// This string is the entire explanation a person gets before deciding, and the
    /// decision is the difference between a working scanner and an empty list.
    static let localNetworkUsage =
        "Zhen scans the network you are connected to so it can list the devices on "
        + "it and read the names they advertise."

    /// The plist, as XML.
    static func xml() -> String {
        let services = BonjourVocabulary.browsedTypes
            .map { "        <string>\($0)</string>" }
            .joined(separator: "\n")
        return """
            <?xml version="1.0" encoding="UTF-8"?>
            <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" \
            "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
            <!--
              GENERATED by `Zhen --print-info-plist`. Do not hand-edit.

              NSBonjourServices comes from BonjourVocabulary.browsedTypes, which is the
              same array the discovery layer iterates. A type that is browsed but not
              declared here returns nothing, silently, with no error anywhere — so the
              two lists are one list.
            -->
            <plist version="1.0">
            <dict>
                <key>CFBundleIdentifier</key>
                <string>\(bundleIdentifier)</string>
                <key>CFBundleName</key>
                <string>\(bundleName)</string>
                <key>CFBundleDisplayName</key>
                <string>\(bundleName)</string>
                <key>CFBundleExecutable</key>
                <string>\(bundleName)</string>
                <key>CFBundlePackageType</key>
                <string>APPL</string>
                <key>CFBundleIconFile</key>
                <string>\(iconFile)</string>
                <key>CFBundleIconName</key>
                <string>AppIcon</string>
                <key>CFBundleShortVersionString</key>
                <string>\(version)</string>
                <key>CFBundleVersion</key>
                <string>\(version)</string>
                <key>LSMinimumSystemVersion</key>
                <string>26.0</string>
                <key>NSHighResolutionCapable</key>
                <true/>
                <key>NSPrincipalClass</key>
                <string>NSApplication</string>
                <key>NSLocalNetworkUsageDescription</key>
                <string>\(localNetworkUsage)</string>
                <key>NSBonjourServices</key>
                <array>
            \(services)
                </array>
            </dict>
            </plist>
            """
    }
}
