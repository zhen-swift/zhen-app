#!/usr/bin/env bash
#
# generate-bonjour-services.sh — write Zhen/Info.plist's NSBonjourServices from zhen-core.
#
# A Bonjour type the app browses but does not declare returns nothing, silently, with no
# error anywhere — it looks exactly like a device that is not there. So the declared list is
# not typed by hand: it is read from `BonjourVocabulary.serviceTypes`, the list core's
# browser iterates, in the zhen-core release this project resolves.
#
# The guarantee is the test, not this script: `InfoPlistTests` reads the BUILT app's array
# and compares it with `BonjourVocabulary.browsedTypes` at runtime. When zhen-core adds a
# type, that test fails and names this script.
#
# Usage:
#   Scripts/generate-bonjour-services.sh                      resolve the pinned zhen-core, then write
#   Scripts/generate-bonjour-services.sh <zhen-core checkout> use that checkout
#   Scripts/generate-bonjour-services.sh --check [checkout]   exit 1 if the plist is stale

set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

check=0
if [ "${1:-}" = --check ]; then check=1; shift; fi

core=${1:-}
if [ -z "$core" ]; then
  packages=$(mktemp -d)
  trap 'rm -rf "$packages"' EXIT
  xcodebuild -resolvePackageDependencies -project Zhen.xcodeproj -scheme Zhen \
    -clonedSourcePackagesDirPath "$packages" > /dev/null
  core="$packages/checkouts/zhen-core"
fi

source="$core/Sources/ZhenCore/Naming/BonjourVocabulary.swift"
[ -f "$source" ] || { echo "generate-bonjour-services: not found: $source"; exit 2; }

# Only the declarations inside `serviceTypes`, in their order: the array index is the rank.
types=$(sed -n '/static let serviceTypes/,/^    \]/p' "$source" \
  | grep -oE 'BonjourServiceType\(name: "[^"]+"' | sed -E 's/.*"([^"]+)"/\1/')
[ -n "$types" ] || { echo "generate-bonjour-services: no service types in $source"; exit 2; }

plist=Zhen/Info.plist
out=$(mktemp)
{
  cat <<'HEAD'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!--
  GENERATED by Scripts/generate-bonjour-services.sh from zhen-core's
  BonjourVocabulary.serviceTypes. Do not edit; rerun the script.

  Merged with the keys Xcode generates from INFOPLIST_KEY_* build settings. This file holds
  only what a build setting cannot: an array.
-->
<plist version="1.0">
<dict>
	<key>NSBonjourServices</key>
	<array>
HEAD
  for t in $types; do printf '\t\t<string>%s</string>\n' "$t"; done
  cat <<'TAIL'
	</array>
</dict>
</plist>
TAIL
} > "$out"

plutil -lint "$out" > /dev/null
count=$(printf '%s\n' $types | wc -l | tr -d ' ')
if [ "$check" = 1 ]; then
  if cmp -s "$out" "$plist"; then
    echo "generate-bonjour-services: $plist matches zhen-core ($count types) — PASS"
    rm -f "$out"; exit 0
  fi
  echo "generate-bonjour-services: $plist is stale against zhen-core ($count types) — FAIL"
  diff "$plist" "$out" || true
  rm -f "$out"; exit 1
fi
mv "$out" "$plist"
echo "generate-bonjour-services: wrote $count types to $plist"
